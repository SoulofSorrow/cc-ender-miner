local config = require("endermine.config")

local M = {}

M.STATE_FILE = "miner.state"
M.JOURNAL_FILE = "miner.pos"
M.STARTUP_DIR = "startup"
M.STARTUP_FILE = "startup/endermine.lua"
M.STATE_FORMAT = 1

--- Write a file so that a crash leaves either the old or the new content.
--- The new content is read back before the old file is replaced, so a full
--- disk can never destroy the last good file.
---@param path string
---@param text string
---@return boolean ok
---@return string|nil err
function M.writeAtomic(path, text)
  local tmp = path .. ".new"
  local handle, err = fs.open(tmp, "w")
  if not handle then
    return false, tostring(err)
  end
  local okWrite, writeErr = pcall(handle.write, text)
  handle.close()
  if not okWrite then
    pcall(fs.delete, tmp)
    return false, tostring(writeErr)
  end
  local check = fs.open(tmp, "r")
  local written = check and check.readAll() or nil
  if check then
    check.close()
  end
  if written ~= text then
    pcall(fs.delete, tmp)
    return false, "file was not written completely (disk full?)"
  end
  if fs.exists(path) then
    fs.delete(path)
  end
  fs.move(tmp, path)
  return true, nil
end

--- Read a serialized table, falling back to an unfinished atomic write.
---@param path string
---@return table|nil
function M.readTable(path)
  for _, candidate in ipairs({ path, path .. ".new" }) do
    if fs.exists(candidate) then
      local handle = fs.open(candidate, "r")
      if handle then
        local content = handle.readAll()
        handle.close()
        local data = textutils.unserialize(content or "")
        if type(data) == "table" then
          return data
        end
      end
    end
  end
  return nil
end

---@param path string
function M.removeFile(path)
  for _, candidate in ipairs({ path, path .. ".new" }) do
    if fs.exists(candidate) then
      fs.delete(candidate)
    end
  end
end

--- Remove everything that belongs to an unfinished job.
function M.clearJob()
  M.removeFile(M.STATE_FILE)
  M.removeFile(M.JOURNAL_FILE)
  M.removeFile(M.STARTUP_FILE)
end

---@return boolean ok
---@return string|nil err
function M.installStartup()
  if not fs.exists(M.STARTUP_DIR) then
    fs.makeDir(M.STARTUP_DIR)
  end
  return M.writeAtomic(
    M.STARTUP_FILE,
    "-- Generated by miner: continues an interrupted mining job after a reboot\n"
      .. "-- or chunk reload. Deleted automatically when the job ends.\n"
      .. 'shell.run("miner", "resume")\n'
  )
end

---@class SavedJob
---@field format integer
---@field version string
---@field cfg MinerConfig
---@field progress table
---@field journal table

--- Load an interrupted job, nil when there is none or it is unusable.
---@return SavedJob|nil job
---@return string|nil err
function M.loadSavedJob()
  local progress = M.readTable(M.STATE_FILE)
  if not progress then
    return nil, nil
  end
  local journal = M.readTable(M.JOURNAL_FILE)
  if not journal then
    return nil, "position journal is missing"
  end
  if progress.format ~= M.STATE_FORMAT then
    return nil, "saved job was written by an incompatible version"
  end
  local cfg = config.merge(config.DEFAULT, progress.cfg)
  local ok, errors = config.validate(cfg)
  if not ok then
    return nil, "saved job has an invalid configuration: " .. table.concat(errors, "; ")
  end
  return { format = progress.format, version = progress.version, cfg = cfg, progress = progress, journal = journal },
    nil
end

return M
